CREATE PROCEDURE dbo.PA_TI_ORDTRA_TINTORERIA_ITEMS_S0002
    @MODO CHAR(1),
    @COD_ORDTRA COD_ORDTRA = '',
    @NUM_SECUENCIA INT = 0,
    @COD_USUARIO COD_USUARIO = '',
    @BUSQUEDA VARCHAR(100) = '',
    @BLOQUEAR BIT = 0
AS
BEGIN
    SET NOCOUNT ON;
    IF @MODO = 'C'
    BEGIN
        SELECT Kind='shrinkTypes', Code=RTRIM(COD_TIPENC), Description=RTRIM(DES_TIPENC) FROM TX_TIPOS_ENC
        UNION ALL SELECT 'widthTypes',RTRIM(TIP_ANCHO),RTRIM(DES_TIPANCHO) FROM TG_TIPANC WHERE TIP_ANCHO <> 'P'
        UNION ALL SELECT 'rejectionReasons',RTRIM(COD_MOTRECHAZO),RTRIM(DES_MOTRECHAZO) FROM TX_MOTIVO_RECHAZO
        ORDER BY Kind,Description;
        RETURN;
    END;
    IF @MODO = 'T'
    BEGIN
        IF LEN(LTRIM(RTRIM(@BUSQUEDA))) < 2
        BEGIN
            SELECT TOP 0 Kind=CONVERT(VARCHAR(20),'fabrics'),Code=COD_TELA,Description=DES_TELA FROM TX_TELA;
            RETURN;
        END;
        SELECT TOP 30 Kind=CONVERT(VARCHAR(20),'fabrics'),Code=RTRIM(COD_TELA),Description=RTRIM(DES_TELA)
        FROM TX_TELA
        WHERE COD_TELA LIKE '%' + @BUSQUEDA + '%' OR DES_TELA LIKE '%' + @BUSQUEDA + '%'
        ORDER BY COD_TELA;
        RETURN;
    END;
    IF @MODO <> 'D'
    BEGIN
        RAISERROR('Modo de consulta inválido.',16,1);
        RETURN;
    END;
    IF @BLOQUEAR=1
    BEGIN
        DECLARE @SECUENCIA INT;
        SELECT @SECUENCIA=NUM_SECUENCIA FROM TI_ORDTRA_TINTORERIA_ITEMS WITH(UPDLOCK,ROWLOCK)
        WHERE COD_ORDTRA=@COD_ORDTRA AND NUM_SECUENCIA=@NUM_SECUENCIA;
    END;
    SELECT I.*,
        QcFabricDescription=T.DES_TELA,
        QcProgrammedWeight=T.GRAMAJE_ACAB,
        QcProgrammedWidth=T.ANCHO_ACAB,
        QcProgrammedShrinkWidth=T.ENCOG_ANCHO,
        QcProgrammedShrinkLength=T.ENCOG_LARGO,
        QcTechnicalWidthType=dbo.tx_extrae_tipo_ancho_tela(I.COD_TELA),
        QcFabricTwist=T.REVIRADO,
        QcPlantWidth=dbo.TI_ORDTRA_ANCHO_PLANTA(I.COD_ORDTRA,I.COD_TELA,I.COD_COMB,I.COD_COLOR),
        QcResidualShrinkWidth=Z.ENCOG_ANCHO_RESIDUALES,
        QcResidualShrinkLength=Z.ENCOG_LARGO_RESIDUALES,
        QcResidualTwist=Z.REVIRADO_RESIDUALES,
        QcAlternativeFabricDescription=ALT.DES_TELA,
        QcCanEdit=CONVERT(BIT,CASE WHEN EXISTS(
            SELECT 1 FROM TX_SEGURIDAD_CAMBIOS_DATOS_TECNICOS_TELA_ACABADA S
            WHERE S.COD_USUARIO=@COD_USUARIO AND (
                S.COD_CLIENTE_TEX='*****' OR (S.COD_CLIENTE_TEX=H.COD_CLIENTE_TEX AND
                    (S.FLG_SOLO_EXTERNAS='N' OR (S.FLG_SOLO_EXTERNAS='S' AND P.FLG_TINTORERIA_PROPIA='N')))
            )
        ) THEN 1 ELSE 0 END)
    FROM TI_ORDTRA_TINTORERIA_ITEMS I
    INNER JOIN TI_ORDTRA_TINTORERIA H ON H.COD_ORDTRA=I.COD_ORDTRA
    LEFT JOIN TX_TELA T ON T.COD_TELA=I.COD_TELA
    LEFT JOIN TX_TELA ALT ON ALT.COD_TELA=I.COD_TELA_RELACIONADA
    LEFT JOIN TI_MAQUINAS_TINTO M ON M.COD_MAQUINA_TINTO=H.COD_MAQUINA_TINTO
    LEFT JOIN TX_PROVEEDOR P ON P.COD_PROVEEDOR=M.COD_PROVEEDOR_TEXTIL
    OUTER APPLY (
        SELECT TOP 1 R.ENCOG_ANCHO_RESIDUALES,R.ENCOG_LARGO_RESIDUALES,R.REVIRADO_RESIDUALES
        FROM TX_ORDTRA_TELAS R
        WHERE R.COD_TIPORDTRA='TI' AND R.COD_ORDTRA=I.COD_ORDTRA AND R.COD_TELA=I.COD_TELA AND R.COD_COMB=I.COD_COMB
        ORDER BY CASE WHEN R.COD_COLOR=I.COD_COLOR THEN 0 ELSE 1 END,R.COD_COLOR
    ) Z
    WHERE I.COD_ORDTRA=@COD_ORDTRA AND I.NUM_SECUENCIA=@NUM_SECUENCIA;
END;
GO
